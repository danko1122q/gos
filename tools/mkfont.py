#!/usr/bin/env python3
"""Build the GOS proportional bitmap fonts (Chicago + Geneva) from the ASCII-art sources in tools/fonts/.

Usage:  python3 tools/mkfont.py             -> write kernel/gfx/fontdata.c
        python3 tools/mkfont.py --check             -> make sure fontdata.c matches the sources (used by make hosttest)
        python3 tools/mkfont.py --preview X.png   -> render sample text (needs Pillow)
        python3 tools/mkfont.py --width chicago "File"   -> text width (for tools/gui_test.py)

Rules: 12-row cell, baseline below row 9. GOS Chicago = base glyphs emboldened (every pixel also sets the pixel to
its right, like QuickDraw bold) + lowercase with x-height 7. GOS Geneva = 1 px strokes, x-height 6.
Advance width = rightmost ink column + 1 + 1 (1 px gap), unless adv=N is given.
Each glyph row is 1 byte (bit 7 = left): 8 px of ink at most, enforced by the assert in build().
Glyph table order: index 0..94 = ASCII 32..126, 95 = check mark (CP437 0xFB), 96 = divide (CP437 0xF6), 97 = plus-minus (CP437 0xF1)."""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
FD = os.path.join(HERE, 'fonts')
H, ASC, NG = 12, 10, 98
FACES = {  # name: (lowercase file, smear, space width)
    'geneva':  ('geneva_lower.txt', 0, 4),
    'chicago': ('chicago_lower.txt', 1, 5),
}


def parse(path):
    out, cur = {}, None
    for ln in open(path, encoding='utf-8').read().split('\n'):
        if cur is None and ln.startswith('#'):      # comments only outside a glyph (pixel rows also start with '#')
            continue
        if ln.startswith('@'):
            p = ln[1:].split()
            code = p[0]
            kv = dict(x.split('=') for x in p[1:])
            cur = {'top': int(kv['top']), 'adv': int(kv['adv']) if 'adv' in kv else None, 'rows': []}
            out[code] = cur
        elif ln.strip() == '':
            cur = None
        elif cur is not None:
            assert set(ln) <= set('#.'), (path, ln)
            cur['rows'].append(ln)
    return out


def index_of(code):
    if code == 'check': return 95
    if code == 'divide': return 96
    if code == 'plusminus': return 97
    c = int(code, 16)
    assert 0x20 <= c <= 0x7E, code
    return c - 32


def build(face):
    lower, smear, spw = FACES[face]
    src = parse(os.path.join(FD, 'common.txt'))
    for k, v in parse(os.path.join(FD, lower)).items():
        assert k not in src, 'duplicate glyph ' + k
        src[k] = v
    src['20'] = {'top': 0, 'adv': spw, 'rows': []}
    width, bits = [0] * NG, [[0] * H for _ in range(NG)]
    for code, g in src.items():
        i = index_of(code)
        right = 0
        for r, ln in enumerate(g['rows']):
            y = g['top'] + r
            assert 0 <= y < H, 'glyph %s falls outside the cell (row %d)' % (code, y)
            v = 0
            for x, ch in enumerate(ln):
                if ch == '#':
                    v |= 1 << (7 - x)
                    if smear:
                        assert x + 1 < 8, 'glyph %s is wider than 8 px after emboldening' % code
                        v |= 1 << (7 - x - 1)
                    assert x < 8, 'glyph %s is wider than 8 px' % code
                    right = max(right, x + 1 + (1 if smear else 0))
            bits[i][y] = v
        width[i] = g['adv'] if g['adv'] is not None else right + 1
    for i in range(NG):
        assert width[i] > 0, 'glyph %d is missing' % i
    return width, bits


def glyph_index(ch):
    c = ord(ch)
    if c == 0xFB: return 95
    if c == 0xF6: return 96
    if c == 0xF1: return 97
    return c - 32 if 32 <= c <= 126 else ord('?') - 32


def text_width(face, s):
    w, _ = build(face)
    return sum(w[glyph_index(c)] for c in s)


def render():
    lines = ['/* GENERATED by tools/mkfont.py from the .txt files in tools/fonts -- do not edit; change the sources and rerun it. */',
             '#include "gfx/font.h"', '']
    for face in ('chicago', 'geneva'):
        w, b = build(face)
        lines.append('const UiFont font_data_%s = {' % face)
        lines.append('    %d, %d, %d, 0,' % (H, ASC, NG))
        lines.append('    { ' + ', '.join(map(str, w)) + ' },')
        lines.append('    { 0, 0, 0 },')
        lines.append('    {')
        for i in range(NG):
            lines.append('        { ' + ', '.join('0x%02X' % v for v in b[i]) + ' },' + ('  /* %c */' % chr(32 + i) if i < 95 else ('  /* check mark */' if i == 95 else '  /* divide */' if i == 96 else '  /* plus-minus */')))
        lines.append('    },')
        lines.append('};')
        lines.append('')
    return '\n'.join(lines)


FONTDATA = os.path.join(HERE, '..', 'kernel', 'gfx', 'fontdata.c')


def emit():
    open(FONTDATA, 'w').write(render())
    print('write', os.path.normpath(FONTDATA))


def check():
    ok = os.path.exists(FONTDATA) and open(FONTDATA).read() == render()
    print('fontdata.c %s' % ('matches tools/fonts' if ok else 'STALE: run make fonts'))
    return 0 if ok else 1


def preview(out):
    from PIL import Image
    S = 3
    samples = ['File  Edit  View  Special', 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz',
               '0123456789 !"#$%&\'()*+,-./:;<=>?@[\\]^_`{|}~ \xfb \xf6 \xf1', 'The quick brown fox jumps over the lazy dog',
               'Empty Trash...  About GOS  Get Info  Control Panel  Jumping Quizzes']
    img = Image.new('RGB', (640 * S // 1, (len(samples) * 2 * 18 + 10) * S), 'white')
    px = img.load()
    y0 = 4
    for face in ('chicago', 'geneva'):
        w, b = build(face)
        for s in samples:
            x = 4
            for ch in s:
                gi = glyph_index(ch)
                for r in range(H):
                    for c in range(8):
                        if b[gi][r] & (0x80 >> c):
                            for dy in range(S):
                                for dx in range(S):
                                    X, Y = (x + c) * S + dx, (y0 + r) * S + dy
                                    if X < img.width: px[X, Y] = (0, 0, 0)
                x += w[gi]
            y0 += 18
    img.save(out)
    print('preview', out)


if __name__ == '__main__':
    a = sys.argv[1:]
    if a[:1] == ['--check']: sys.exit(check())
    elif a[:1] == ['--preview']: preview(a[1])
    elif a[:1] == ['--width']: print(text_width(a[1], a[2]))
    else: emit()
