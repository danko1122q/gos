#!/usr/bin/env python3
"""Generate kernel/drivers/arm/font8x16.c (256 glyphs, 8x16, CP437 order) from GNU Unifont.
GNU Unifont (c) Roman Czyborra, Paul Hardy, et al.; licensed GPLv2+ with the font exception (see /usr/share/doc/fonts-unifont/copyright).
Usage: tools/mkfont8x16.py [unifont.otf] > kernel/drivers/arm/font8x16.c"""
import sys
from PIL import Image, ImageDraw, ImageFont

path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/unifont/unifont.otf"
font = ImageFont.truetype(path, 16)

def glyph(ch):
    im = Image.new("L", (16, 16), 0)
    ImageDraw.Draw(im).text((0, 0), ch, font=font, fill=255, anchor="la")
    rows = []
    for y in range(16):
        b = 0
        for x in range(8):
            if im.getpixel((x, y)) >= 128:
                b |= 0x80 >> x
        rows.append(b)
    return rows

def char_for(i):
    if i == 0: return " "
    if i < 32 or i == 127 or i >= 128:
        return bytes([i]).decode("cp437")
    return chr(i)

print("/* GENERATED by tools/mkfont8x16.py from GNU Unifont (GPLv2+ with the font exception) - do not edit by hand. */")
print('#include "arch/arch.h"')
print("const u8 font8x16[256 * 16] = {")
for i in range(256):
    g = glyph(char_for(i))
    print("    " + ",".join("0x%02X" % b for b in g) + ",")
print("};")
